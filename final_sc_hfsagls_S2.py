# 7.  DECODIFICADOR / SIMULADOR HFS CON SUBLOTES CONSISTENTES
# ---------------------------------------------------------------------------

def _primer_hueco(intervalos: List[Tuple[float, float]], t_listo: float,
                  duracion: float) -> float:
    """
    Primer instante >= t_listo en que la máquina tiene un hueco libre de
    longitud 'duracion' ("first available position" del artículo).
    """
    t = t_listo
    for ini, fin in intervalos:
        if t + duracion <= ini + 1e-9:
            return t
        if fin > t:
            t = fin
    return t


def simular_hfs(individuo: dict) -> Tuple[Dict[str, float], Dict[int, list]]:
    """
    Decodifica el cromosoma (esquema de programación serial, etapa por etapa).

    Para cada etapa s y cada sublote (j,b) en el orden del nivel 2:
      * tiempo listo = fin del MISMO sublote (j,b) en la etapa anterior
        (o la liberación del trabajo en la primera etapa),
      * máquina = nivel 3 del cromosoma (o ECT si ASIGNACION_MAQUINAS='ECT'),
      * se programa en el primer hueco disponible de la máquina.
    El tamaño del sublote es el mismo en todas las etapas (consistente).

    En las etapas con alistamiento (ALISTAMIENTO_MIN_POR_ETAPA), cada sublote
    se programa a continuación del último trabajo de la máquina, y se suma el
    alistamiento si la referencia cambia. El alistamiento puede hacerse
    mientras el sublote llega (anticipatorio): inicia cuando la máquina queda
    libre. La regla ECT compara el tiempo de terminación incluido el
    alistamiento.

    Retorna
    -------
    C     : {trabajo: tiempo_de_terminación_en_última_etapa}
    gantt : {etapa: [(trabajo, sublote, maquina, inicio, fin), ...],
             'alistamientos': [(etapa, maquina, inicio, fin), ...]}
    """
    k        = individuo['k']
    maquinas = individuo.get('maquinas')

    doc = {j: props_a_docenas(j, individuo['proporciones'][j]) for j in TRABAJOS}

    # Tiempo en que cada sublote queda disponible para la siguiente etapa
    listo = {(j, b): RELEASE[j] for j in TRABAJOS for b in range(1, k[j] + 1)}

    agenda: Dict[str, List[Tuple[float, float]]] = {}
    gantt: Dict = {s: [] for s in ETAPAS}
    gantt['alistamientos'] = []

    for s in ETAPAS:
        fin_s = {}
        setup_h = ALISTAMIENTO_MIN_POR_ETAPA.get(NOMBRE_ETAPA[s], 0.0) / 60.0
        ultimo: Dict[str, Tuple[str, float]] = {}   # máquina → (referencia, fin)
        for (j, b) in individuo['posiciones'][s]:
            cant = doc[j][b - 1]
            if cant <= 0:
                fin_s[(j, b)] = listo[(j, b)]
                continue
            t_listo = listo[(j, b)]

            if maquinas is not None:
                candidatas = [maquinas[s][(j, b)]]
            else:
                candidatas = elegibles(j, s)

            mejor = None
            for m in candidatas:
                p = tiempo_horas(j, m, cant)
                if setup_h > 0:
                    prev = ultimo.get(m)
                    libre = prev[1] if prev else 0.0
                    cambia = (prev is None and ALISTAMIENTO_INICIAL) or \
                             (prev is not None and prev[0] != PRODUCTO[j])
                    su = setup_h if cambia else 0.0
                    ini = max(libre + su, t_listo)
                    cand = (m, ini, ini + p, libre, su)
                else:
                    ini = _primer_hueco(agenda.get(m, []), t_listo, p)
                    cand = (m, ini, ini + p, None, 0.0)
                # 'FAM' (primera máquina disponible): gana la que permite
                # iniciar antes. ECT: gana la que termina antes.
                crit = 1 if individuo.get('regla_maquina') == 'FAM' else 2
                if mejor is None or cand[crit] < mejor[crit] - 1e-9:
                    mejor = cand
            m, ini, fin, libre, su = mejor

            if setup_h > 0:
                ultimo[m] = (PRODUCTO[j], fin)
                if su > 0:
                    gantt['alistamientos'].append((s, m, libre, libre + su))
            else:
                bisect.insort(agenda.setdefault(m, []), (ini, fin))
            fin_s[(j, b)] = fin
            gantt[s].append((j, b, m, ini, fin))
        listo = fin_s

    C = {j: max(listo[(j, b)] for b in range(1, k[j] + 1)) for j in TRABAJOS}
    return C, gantt

