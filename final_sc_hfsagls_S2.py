def secuencias_reglas() -> Dict[str, List[str]]:
    """
    Secuencias de las reglas de despacho evaluadas:
      FIFO → orden de llegada (orden de la hoja de trabajos)
      EDD  → fecha de entrega más temprana
      SPT  → menor tiempo total de proceso
      LPT  → mayor tiempo total de proceso
      MST  → menor holgura (d_j − p_j)
      CR   → menor razón crítica (d_j / p_j)
    """
    p = calcular_tiempos_completos()
    P = {j: sum(p[j][s] for s in ETAPAS) for j in TRABAJOS}
    return {
        "FIFO": list(TRABAJOS),
        "EDD" : sorted(TRABAJOS, key=lambda j: DUE_DATE[j]),
        "SPT" : sorted(TRABAJOS, key=lambda j: P[j]),
        "LPT" : sorted(TRABAJOS, key=lambda j: P[j], reverse=True),
        "MST" : sorted(TRABAJOS, key=lambda j: DUE_DATE[j] - P[j]),
        "CR"  : sorted(TRABAJOS, key=lambda j: DUE_DATE[j] / P[j]),
    }


def evaluar_reglas(con_lot_streaming: bool = False) -> List[dict]:
    """
    Evalúa las reglas de despacho sin lot streaming (lote completo) o con
    los sublotes del escenario 2 (B sublotes iguales por lote).
    """
    resultados = []
    for nombre, seq in secuencias_reglas().items():
        if con_lot_streaming:
            C, _ = simular_hfs(individuo_regla_ls(seq))
        else:
            C, _ = simular_sin_ls(seq)
        ind = calcular_indicadores(C)
        resultados.append({'regla': nombre, 'secuencia': seq, **ind})
    return resultados


def mejor_de(resultados: List[dict]) -> dict:
    """Regla con mejor desempeño según la función objetivo."""
    if FUNCION_OBJETIVO == 'Cmax':
        return min(resultados, key=lambda x: (x['Cmax'], x['suma_Ti']))
    return min(resultados, key=lambda x: (x['suma_Ti'], x['Cmax']))

