def docenas(pares: float) -> float:
    """Convierte pares de guantes a docenas (1 docena = 12 pares)."""
    return pares / 12.0


def tiempo_horas(trabajo: str, maquina: str, cant_docenas: float) -> float:
    """
    Tiempo de procesamiento de cant_docenas del trabajo en la máquina [horas].
    Fórmula: (min/docena) × docenas / 60
    """
    return (TIEMPO_MIN_DOCENA[(PRODUCTO[trabajo], maquina)] * cant_docenas) / 60.0


def elegibles(trabajo: str, etapa: int) -> List[str]:
    """Máquinas de la etapa capaces de procesar el producto del trabajo."""
    return ELEGIBLES[(PRODUCTO[trabajo], etapa)]


def tiempo_lote_etapa(trabajo: str, etapa: int) -> float:
    """Tiempo [h] del lote completo en la máquina más rápida de la etapa."""
    doc = docenas(DEMANDA[trabajo])
    return min(tiempo_horas(trabajo, m, doc) for m in elegibles(trabajo, etapa))


def calcular_tiempos_completos() -> Dict[str, Dict[int, float]]:
    """Retorna p[trabajo][etapa] = tiempo total [horas] del lote completo."""
    return {j: {s: tiempo_lote_etapa(j, s) for s in ETAPAS} for j in TRABAJOS}

