def graficar_gantt(individuo: dict,
                   titulo: str = "Diagrama de Gantt — HFS con Sublotes Consistentes",
                   guardar_como: str = None):
    """
    Genera el diagrama de Gantt de la solución con sublotes consistentes.
    """

    # ── Simular para obtener el Gantt ──
    C, gantt = simular_hfs(individuo)
    ind      = calcular_indicadores(C)
    cmax     = ind['Cmax']

    # ── Paleta de colores (un color por trabajo) ──
    colores_base = [
        '#4E79A7',  # azul     → Trabajo 1
        '#F28E2B',  # naranja  → Trabajo 2
        '#59A14F',  # verde    → Trabajo 3
        '#E15759',  # rojo     → Trabajo 4
        '#B07AA1',  # morado   → Trabajo 5
        '#76B7B2',  # turquesa → Trabajo 6
        '#EDC948',  # amarillo → Trabajo 7
        '#FF9DA7',  # rosa     → Trabajo 8
        '#9C755F',  # marrón   → Trabajo 9
        '#BAB0AC',  # gris     → Trabajo 10
    ]
    color_trabajo = {
        j: colores_base[i % len(colores_base)]
        for i, j in enumerate(TRABAJOS)
    }

    n_etapas = len(ETAPAS)

    # ── Determinar qué máquinas realmente se usaron en cada etapa ──
    maquinas_usadas = {}
    for s in ETAPAS:
        usadas = sorted(set(m for (j, b, m, ini, fin) in gantt[s]),
                        key=_clave_maquina)
        maquinas_usadas[s] = usadas

    # ── Calcular altura proporcional de cada subgráfico ──
    alturas = [max(1, len(maquinas_usadas[s])) for s in ETAPAS]
    total_filas = sum(alturas)

    # ── Crear figura ──
    alto_por_fila = 0.40          # pulgadas por fila de máquina
    ancho_fig     = 20            # ancho total de la figura
    alto_fig      = max(8, total_filas * alto_por_fila + 3)

    fig, axes = plt.subplots(
        n_etapas, 1,
        figsize=(ancho_fig, alto_fig),
        gridspec_kw={'height_ratios': alturas},
        sharex=True
    )
    if n_etapas == 1:
        axes = [axes]

    fig.suptitle(titulo, fontsize=14, fontweight='bold', y=1.0)

    umbral_texto = (cmax if cmax > 0 else 1) * 0.025  # mínimo ancho para poner texto

    for idx, s in enumerate(ETAPAS):
        ax       = axes[idx]
        maquinas = maquinas_usadas[s]
        n_maq    = len(maquinas)

        # Mapa: máquina → posición en el eje Y (0-based desde abajo)
        pos_maq  = {m: i for i, m in enumerate(maquinas)}

        # ── Dibujar barras ──
        for (j, b, m, ini, fin) in gantt[s]:
            y_pos    = pos_maq[m]
            dur      = fin - ini
            color    = color_trabajo[j]

            ax.barh(
                y_pos, dur, left=ini,
                height=0.72,
                color=color,
                edgecolor='white',
                linewidth=0.6,
                alpha=0.92
            )

            if dur >= umbral_texto:
                ax.text(
                    ini + dur / 2, y_pos,
                    f"{j}-S{b}",
                    ha='center', va='center',
                    fontsize=6.5, fontweight='bold',
                    color='white',
                    clip_on=True
                )

        # ── Alistamientos (barras rayadas) ──
        for (s_al, m_al, a_ini, a_fin) in gantt.get('alistamientos', []):
            if s_al == s and m_al in pos_maq:
                ax.barh(pos_maq[m_al], a_fin - a_ini, left=a_ini, height=0.72,
                        color='white', edgecolor='#555555', hatch='////',
                        linewidth=0.4)

        # ── Línea vertical de Cmax ──
        ax.axvline(cmax, color='#333333', linewidth=1.2,
                   linestyle='--', alpha=0.7)

        # ── Eje Y: etiquetas de máquinas ──
        ax.set_yticks(range(n_maq))
        ax.set_yticklabels(maquinas, fontsize=8)
        ax.set_ylim(-0.6, max(n_maq, 1) - 0.4)
        ax.set_ylabel(f"Etapa {s} — {NOMBRE_ETAPA[s]}", fontsize=9,
                      fontweight='bold', labelpad=8)

        # ── Cuadrícula y estética ──
        ax.xaxis.set_minor_locator(ticker.AutoMinorLocator(4))
        ax.grid(axis='x', which='major', linestyle='--',
                linewidth=0.5, alpha=0.5, color='#bbbbbb')
        ax.grid(axis='x', which='minor', linestyle=':',
                linewidth=0.3, alpha=0.35, color='#cccccc')
        ax.set_facecolor('#F8F9FA')
        ax.spines['top'].set_visible(False)
        ax.spines['right'].set_visible(False)

        # ── Anotación de Cmax solo en la última etapa ──
        if idx == n_etapas - 1:
            ax.annotate(
                f"Cmax = {cmax:.2f} h",
                xy=(cmax, -0.55),
                xytext=(cmax - (cmax * 0.01), -0.55),
                fontsize=8, color='#333333',
                ha='right'
            )

    # ── Eje X compartido ──
    axes[-1].set_xlabel("Tiempo (horas laborables)", fontsize=10)
    axes[-1].xaxis.set_major_locator(ticker.MaxNLocator(integer=False, nbins=15))

    # ── Leyenda de trabajos ──
    parches_leyenda = [
        mpatches.Patch(color=color_trabajo[j], label=f"{j} ({PRODUCTO[j]})")
        for j in TRABAJOS
    ]
    if gantt.get('alistamientos'):
        parches_leyenda.append(mpatches.Patch(facecolor='white', edgecolor='#555555',
                                              hatch='////', label='Alistamiento'))
    fig.legend(
        handles=parches_leyenda,
        loc='lower center',
        ncol=min(len(parches_leyenda), 11),
        fontsize=9,
        frameon=True,
        framealpha=0.9,
        edgecolor='#cccccc',
        bbox_to_anchor=(0.5, 0.0)
    )

    # ── Información de la solución ──
    info = (
        f"Sublotes por orden = {NUM_SUBLOTES}  |  "
        f"ΣTj = {ind['suma_Ti']:.2f} h  |  "
        f"Cmax = {cmax:.2f} h  |  "
        f"Órdenes tardías = {ind['num_tardy']}"
    )
    fig.text(0.5, 1.002, info, ha='center', va='bottom',
             fontsize=8.5, color='#444444',
             transform=fig.transFigure)

    plt.tight_layout(rect=[0, 0.025, 1, 0.99])

    # ── Guardar y/o mostrar ──
    # Se guarda ANTES de plt.show(): en algunos entornos show() libera la
    # figura y el PNG quedaría en blanco.
    if guardar_como:
        fig.savefig(guardar_como, dpi=150, bbox_inches='tight')
        print(f"  Gantt guardado en: {guardar_como}")

    plt.show()

    return fig

