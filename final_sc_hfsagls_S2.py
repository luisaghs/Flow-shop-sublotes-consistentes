def calcular_indicadores(C: Dict[str, float]) -> Dict:
    """
    Calcula todos los indicadores de desempeño estándar de scheduling.
    """
    ind_j = {}
    for j in TRABAJOS:
        ci = C[j]
        ri = RELEASE[j]
        di = DUE_DATE[j]
        li = ci - di
        ti = max(0.0, li)
        ei = max(0.0, -li)
        ind_j[j] = {
            'Ci': ci, 'ri': ri, 'di': di,
            'Fi': ci - ri, 'Li': li, 'Ti': ti,
            'Ei': ei, 'delta_i': 1 if ti > 1e-9 else 0,
        }

    return {
        'por_trabajo': ind_j,
        'Cmax'      : max(C[j] for j in TRABAJOS),
        'Lmax'      : max(ind_j[j]['Li'] for j in TRABAJOS),
        'Tmax'      : max(ind_j[j]['Ti'] for j in TRABAJOS),
        'suma_Ti'   : sum(ind_j[j]['Ti'] for j in TRABAJOS),
        'suma_Ei'   : sum(ind_j[j]['Ei'] for j in TRABAJOS),
        'suma_Fi'   : sum(ind_j[j]['Fi'] for j in TRABAJOS),
        'media_Fi'  : sum(ind_j[j]['Fi'] for j in TRABAJOS) / len(TRABAJOS),
        'num_tardy' : sum(ind_j[j]['delta_i'] for j in TRABAJOS),
    }


def evaluar(individuo: dict) -> Tuple[float, float]:
    """(ΣTi, Cmax) del individuo, cacheado para evitar re-evaluaciones."""
    if '_eval' not in individuo:
        C, _ = simular_hfs(individuo)
        ind = calcular_indicadores(C)
        individuo['_eval'] = (ind['suma_Ti'], ind['Cmax'])
    return individuo['_eval']


def fitness(individuo: dict) -> Tuple[float, float]:
    """
    Aptitud lexicográfica (menor = mejor).
    Con FUNCION_OBJETIVO='suma_Ti' → (ΣTi, Cmax): si varias soluciones no
    tienen tardanza, se prefiere la de menor makespan.
    """
    sum_ti, cmax = evaluar(individuo)
    sum_ti = round(sum_ti, 6)
    cmax   = round(cmax, 6)
    return (cmax, sum_ti) if FUNCION_OBJETIVO == 'Cmax' else (sum_ti, cmax)

