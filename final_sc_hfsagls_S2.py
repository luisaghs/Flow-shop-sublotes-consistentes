def _min_unidades() -> int:
    """Tamaño mínimo de sublote expresado en unidades de GRANULARIDAD_PARES."""
    return max(1, math.ceil(MIN_DOCENAS_POR_SUBLOTE * 12 / GRANULARIDAD_PARES))


def num_sublotes(trabajo: str) -> int:
    """
    Número de sublotes del lote (B del artículo).
    En el escenario 2 es fijo e igual a NUM_SUBLOTES; solo se reduce si el
    lote no alcanza para NUM_SUBLOTES sublotes del tamaño mínimo.
    """
    por_volumen = (DEMANDA[trabajo] // GRANULARIDAD_PARES) // _min_unidades()
    return max(1, min(NUM_SUBLOTES, por_volumen))


def _dirichlet(k: int) -> List[float]:
    """
    k proporciones aleatorias (tamaños variables del escenario 2).
    Garantiza que ninguna proporción sea numéricamente cero.
    """
    muestras = [random.expovariate(1.0) for _ in range(k)]
    total = sum(muestras)
    props = [max(m / total, 1e-9) for m in muestras]
    # Renormalizar tras el clamp
    total2 = sum(props)
    return [p / total2 for p in props]


def props_a_pares(trabajo: str, props: List[float]) -> List[int]:
    """
    Convierte las proporciones del nivel 1 en tamaños de sublote LS_b [pares].

    * Cada sublote tiene al menos MIN_DOCENAS_POR_SUBLOTE.
    * Los tamaños son múltiplos de GRANULARIDAD_PARES (método del mayor
      residuo) y su suma es exactamente la demanda del lote (ec. (5)).
    """
    total    = DEMANDA[trabajo]
    k        = len(props)
    unidades = total // GRANULARIDAD_PARES
    residuo  = total - unidades * GRANULARIDAD_PARES
    min_u    = _min_unidades()

    if k == 1 or unidades < k * min_u:
        # No hay volumen para repartir respetando el mínimo: un solo bloque
        tam = [0] * k
        tam[0] = total
        return tam

    libres  = unidades - k * min_u
    crudos  = [p * libres for p in props]
    base    = [int(math.floor(x)) for x in crudos]
    faltan  = libres - sum(base)
    orden   = sorted(range(k), key=lambda i: crudos[i] - base[i], reverse=True)
    for i in orden[:faltan]:
        base[i] += 1

    tam = [(min_u + u) * GRANULARIDAD_PARES for u in base]
    tam[-1] += residuo
    return tam


def props_a_docenas(trabajo: str, props: List[float]) -> List[float]:
    """Tamaños de sublote en docenas."""
    return [docenas(p) for p in props_a_pares(trabajo, props)]


def _sublotes(k: Dict[str, int]) -> List[Tuple[str, int]]:
    """Lista de todos los sublotes (j, b) según el número de sublotes k."""
    return [(j, b) for j in TRABAJOS for b in range(1, k[j] + 1)]


def _reparar(ind: dict) -> None:
    """
    Asegura que los niveles 2 y 3 contengan exactamente los sublotes del
    nivel 1 (cada sublote una vez por etapa y con máquina asignada).
    """
    validos = set(_sublotes(ind['k']))
    for s in ETAPAS:
        orden, vistos = [], set()
        for sb in ind['posiciones'][s]:
            if sb in validos and sb not in vistos:
                orden.append(sb)
                vistos.add(sb)
        for (j, b) in sorted(validos - vistos, key=lambda x: (x[0], x[1])):
            if (j, b - 1) in vistos:
                pos = orden.index((j, b - 1)) + 1
            else:
                pos = random.randint(0, len(orden))
            orden.insert(pos, (j, b))
            vistos.add((j, b))
        ind['posiciones'][s] = orden

        if ind.get('maquinas') is not None:
            maqs = {sb: m for sb, m in ind['maquinas'][s].items() if sb in validos}
            # Se recorre en orden fijo (no el set) para que la semilla sea reproducible
            for (j, b) in orden:
                if (j, b) not in maqs:
                    maqs[(j, b)] = random.choice(elegibles(j, s))
            ind['maquinas'][s] = maqs


def crear_individuo() -> dict:
    """
    Población inicial del ESCENARIO 2 (asignación aleatoria):
      - Nivel 1: B sublotes por lote con tamaños variables (aleatorios),
                 iguales en todas las etapas.
      - Nivel 2: posiciones de los sublotes aleatorias en cada etapa.
      - Nivel 3: máquinas capaces asignadas aleatoriamente
                 (solo si ASIGNACION_MAQUINAS = 'cromosoma').
    """
    k, proporciones = {}, {}
    for j in TRABAJOS:
        k[j] = num_sublotes(j)
        proporciones[j] = _dirichlet(k[j])

    subs = _sublotes(k)
    posiciones, maquinas = {}, {}
    for s in ETAPAS:
        orden = subs[:]
        random.shuffle(orden)
        posiciones[s] = orden
        maquinas[s] = {(j, b): random.choice(elegibles(j, s)) for (j, b) in subs}

    return {
        'k'           : k,
        'proporciones': proporciones,
        'posiciones'  : posiciones,
        'maquinas'    : maquinas if ASIGNACION_MAQUINAS == 'cromosoma' else None,
    }

