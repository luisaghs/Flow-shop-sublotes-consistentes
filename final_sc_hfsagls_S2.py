def individuo_situacion_actual() -> dict:
    """
    Programación actual de la empresa (línea base):
      * secuencia FIFO: las órdenes se atienden en orden de llegada;
      * cada orden se reparte docena a docena entre las máquinas de cada
        etapa, en la máquina que esté disponible (primera máquina disponible),
        hasta completar el lote; luego continúa la orden siguiente;
      * se respeta el alistamiento de troquelado.
    """
    k = {j: max(1, round(DEMANDA[j] / 12)) for j in TRABAJOS}
    return {
        'k'            : k,
        'proporciones' : {j: [1.0 / k[j]] * k[j] for j in TRABAJOS},
        'posiciones'   : {s: [(j, b) for j in TRABAJOS for b in range(1, k[j] + 1)]
                          for s in ETAPAS},
        'maquinas'     : None,
        'regla_maquina': 'FAM',
    }


def evaluar_situacion_actual() -> dict:
    """Indicadores de la programación actual (FIFO docena a docena)."""
    C, _ = simular_hfs(individuo_situacion_actual())
    return {'regla': 'FIFO docena a docena', 'secuencia': list(TRABAJOS),
            **calcular_indicadores(C)}


def individuo_sin_ls(secuencia: List[str]) -> dict:
    """
    Individuo del HFS clásico sin lot streaming: un solo sublote por lote,
    mismo orden en todas las etapas y máquina elegida por ECT.
    """
    return {
        'k'           : {j: 1 for j in TRABAJOS},
        'proporciones': {j: [1.0] for j in TRABAJOS},
        'posiciones'  : {s: [(j, 1) for j in secuencia] for s in ETAPAS},
        'maquinas'    : None,
    }


def simular_sin_ls(secuencia: List[str]) -> Tuple[Dict[str, float], Dict]:
    """Simula el HFS clásico sin lot streaming (k=1 en todas las etapas)."""
    return simular_hfs(individuo_sin_ls(secuencia))


def individuo_regla_ls(secuencia: List[str]) -> dict:
    """
    Individuo con los sublotes del escenario 2 (B sublotes por lote, de igual
    tamaño) procesados en el orden de la regla, el mismo en todas las etapas.
    La máquina se elige por ECT; si ASIGNACION_MAQUINAS = 'cromosoma', esas
    máquinas se copian al nivel 3 para que el individuo sea válido en el GA.
    """
    k = {j: num_sublotes(j) for j in TRABAJOS}
    ind = {
        'k'           : k,
        'proporciones': {j: [1.0 / k[j]] * k[j] for j in TRABAJOS},
        'posiciones'  : {s: [(j, b) for j in secuencia for b in range(1, k[j] + 1)]
                         for s in ETAPAS},
        'maquinas'    : None,
    }
    if ASIGNACION_MAQUINAS == 'cromosoma':
        _, gantt = simular_hfs(ind)
        ind['maquinas'] = {s: {(j, b): m for (j, b, m, _, _) in gantt[s]}
                           for s in ETAPAS}
    return ind

