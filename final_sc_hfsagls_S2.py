def seleccion_torneo(poblacion: List[dict], tam: int) -> dict:
    """Selección por torneo de tamaño 'tam'."""
    return min(random.sample(poblacion, tam), key=fitness)


def _cruce_proporciones(a: List[float], b: List[float]
                        ) -> Tuple[List[float], List[float]]:
    """
    Cruce aritmético del nivel 1 para un lote (a y b tienen B elementos).

    Con α ~ U(GA_PARAMS['alfa_cruce']):
        hijo 1 = α·a + (1−α)·b
        hijo 2 = (1−α)·a + α·b
    Los hijos son complementarios y distintos entre sí, y la suma de
    proporciones de cada hijo sigue siendo 1.
    """
    alfa = random.uniform(*GA_PARAMS['alfa_cruce'])
    h1 = [alfa * x + (1 - alfa) * y for x, y in zip(a, b)]
    h2 = [(1 - alfa) * x + alfa * y for x, y in zip(a, b)]
    return h1, h2


def _puntos_cruce() -> List[int]:
    """
    Etapas que el hijo 1 hereda del padre 1 (el resto, del padre 2).
      C1 (un punto) : etapas antes de pp
      C2 (dos puntos): etapas antes de pp1 y desde pp2
    """
    n = len(ETAPAS)
    if n < 2:
        return list(range(n))
    if GA_PARAMS['tipo_cruce'] == 'C2' and n >= 3:
        pp1, pp2 = sorted(random.sample(range(1, n), 2))
        return list(range(0, pp1)) + list(range(pp2, n))
    pp = random.randint(1, n - 1)
    return list(range(0, pp))


def cruce(p1: dict, p2: dict) -> Tuple[dict, dict]:
    """
    Cruce sobre los tres niveles del cromosoma.

    Nivel 1 (tamaños consistentes): el número de sublotes es fijo (S2); por
            lote se aplica un cruce aritmético con α aleatorio, que da dos
            hijos distintos (ver _cruce_proporciones).
    Niveles 2 y 3: cruce de uno (C1) o dos puntos (C2) por etapas, como en
            el artículo; luego se reparan para que sean coherentes con el
            nivel 1 del hijo.
    """
    h1 = copy.deepcopy(p1)
    h2 = copy.deepcopy(p2)
    h1.pop('_eval', None)
    h2.pop('_eval', None)

    # 1. Nivel 1 — independiente por lote
    for j in TRABAJOS:
        h1['proporciones'][j], h2['proporciones'][j] = _cruce_proporciones(
            p1['proporciones'][j], p2['proporciones'][j])

    # 2. Niveles 2 y 3 — por bloques de etapas
    del_padre = set(_puntos_cruce())
    for idx, s in enumerate(ETAPAS):
        if idx in del_padre:
            continue
        h1['posiciones'][s] = p2['posiciones'][s][:]
        h2['posiciones'][s] = p1['posiciones'][s][:]
        if h1.get('maquinas') is not None:
            h1['maquinas'][s] = dict(p2['maquinas'][s])
            h2['maquinas'][s] = dict(p1['maquinas'][s])

    _reparar(h1)
    _reparar(h2)
    return h1, h2


def mutar(individuo: dict) -> dict:
    """
    Mutación sobre los tres niveles (el número de sublotes no cambia: S2).
    """
    ind = copy.deepcopy(individuo)
    ind.pop('_eval', None)

    # 1. Nivel 2: swap de dos posiciones en una etapa (mutación del artículo)
    if random.random() < GA_PARAMS['prob_mut_pos']:
        s = random.choice(ETAPAS)
        orden = ind['posiciones'][s]
        if len(orden) >= 2:
            a, b = random.sample(range(len(orden)), 2)
            orden[a], orden[b] = orden[b], orden[a]

    # 2. Nivel 3: reasignar la máquina de un sublote en una etapa
    if ind.get('maquinas') is not None and random.random() < GA_PARAMS['prob_mut_maq']:
        s = random.choice(ETAPAS)
        j, b = random.choice(ind['posiciones'][s])
        ind['maquinas'][s][(j, b)] = random.choice(elegibles(j, s))

    # 3. Nivel 1: perturbación gaussiana de un tamaño (igual en todas las etapas)
    for j in TRABAJOS:
        if random.random() < GA_PARAMS['prob_mut_prop']:
            k = ind['k'][j]
            props = ind['proporciones'][j][:]
            idx = random.randrange(k)
            props[idx] = max(1e-9, props[idx] + random.gauss(0, 0.15))
            t = sum(props)
            ind['proporciones'][j] = [p / t for p in props]

    _reparar(ind)
    return ind

