def evaluar_reglas() -> List[dict]:
    """Evalúa EDD, SPT, LPT y FIFO sin lot streaming."""
    p = calcular_tiempos_completos()
    reglas = {
        "EDD" : sorted(TRABAJOS, key=lambda j: DUE_DATE[j]),
        "SPT" : sorted(TRABAJOS, key=lambda j: sum(p[j][s] for s in ETAPAS)),
        "LPT" : sorted(TRABAJOS, key=lambda j: sum(p[j][s] for s in ETAPAS),
                       reverse=True),
        "FIFO": list(TRABAJOS),
    }
    resultados = []
    for nombre, seq in reglas.items():
        C, _ = simular_sin_ls(seq)
        ind = calcular_indicadores(C)
        resultados.append({'regla': nombre, 'secuencia': seq, **ind})
    return resultados

