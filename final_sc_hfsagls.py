    imprimir_tiempos()

    # ── Reglas de despacho sin lot streaming (referencia) ──
    resultados_reglas = evaluar_reglas()
    imprimir_reglas(resultados_reglas)

    if FUNCION_OBJETIVO == 'Cmax':
        mejor_regla = min(resultados_reglas, key=lambda x: (x['Cmax'], x['suma_Ti']))
