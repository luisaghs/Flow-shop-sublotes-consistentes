# 6.  REPRESENTACIÓN DEL CROMOSOMA (SUBLOTES CONSISTENTES — ESCENARIO 2)
# ---------------------------------------------------------------------------
#
#  individuo = {
#    'k'           : {j: B_j}                número de sublotes del lote j
#    'proporciones': {j: [p_1..p_Bj]}        NIVEL 1 → tamaños relativos;
#                                            son los MISMOS en todas las etapas
#    'posiciones'  : {s: [(j,b), ...]}       NIVEL 2 → orden de los sublotes
#                                            en cada etapa
#    'maquinas'    : {s: {(j,b): m}}         NIVEL 3 → máquina por sublote
#                                            y etapa
#  }
# ---------------------------------------------------------------------------

def _min_unidades() -> int:
    """Tamaño mínimo de sublote expresado en unidades de GRANULARIDAD_PARES."""
    return max(1, math.ceil(MIN_DOCENAS_POR_SUBLOTE * 12 / GRANULARIDAD_PARES))


def _max_k_valido(trabajo: str) -> int:
    """
    Número máximo de sublotes permitido para el lote del trabajo.
    Con sublotes consistentes el número de sublotes es el mismo en todas
    las etapas, por lo que se limita por: MAX_SUBLOTES, la etapa con menos
    máquinas capaces y el tamaño mínimo de sublote.
    """
    por_maquinas = min(len(elegibles(trabajo, s)) for s in ETAPAS)
    por_volumen  = (DEMANDA[trabajo] // GRANULARIDAD_PARES) // _min_unidades()
    return max(1, min(MAX_SUBLOTES, por_maquinas, por_volumen))


def _dirichlet(k: int) -> List[float]:
    """
    k proporciones aleatorias.
    Garantiza que ninguna proporción sea numéricamente cero.
    """
    muestras = [random.expovariate(1.0) for _ in range(k)]
    total = sum(muestras)
    props = [max(m / total, 1e-9) for m in muestras]
    # Renormalizar tras el clamp
    total2 = sum(props)
    return [p / total2 for p in props]


def props_a_pares(trabajo: str, props: List[float]) -> List[int]:
    """
    Convierte las proporciones del nivel 1 en tamaños de sublote LS_b [pares].

    * Cada sublote tiene al menos MIN_DOCENAS_POR_SUBLOTE.
    * Los tamaños son múltiplos de GRANULARIDAD_PARES (método del mayor
      residuo) y su suma es exactamente la demanda del lote (ec. (5)).
    """
    total    = DEMANDA[trabajo]
    k        = len(props)
    unidades = total // GRANULARIDAD_PARES
    residuo  = total - unidades * GRANULARIDAD_PARES
    min_u    = _min_unidades()

    if k == 1 or unidades < k * min_u:
        # No hay volumen para repartir respetando el mínimo: un solo bloque
        tam = [0] * k
        tam[0] = total
        return tam

    libres  = unidades - k * min_u
    crudos  = [p * libres for p in props]
    base    = [int(math.floor(x)) for x in crudos]
    faltan  = libres - sum(base)
    orden   = sorted(range(k), key=lambda i: crudos[i] - base[i], reverse=True)
    for i in orden[:faltan]:
        base[i] += 1

    tam = [(min_u + u) * GRANULARIDAD_PARES for u in base]
    tam[-1] += residuo
    return tam


def props_a_docenas(trabajo: str, props: List[float]) -> List[float]:
    """Tamaños de sublote en docenas."""
    return [docenas(p) for p in props_a_pares(trabajo, props)]


def _sublotes(k: Dict[str, int]) -> List[Tuple[str, int]]:
    """Lista de todos los sublotes (j, b) según el número de sublotes k."""
    return [(j, b) for j in TRABAJOS for b in range(1, k[j] + 1)]


def _reparar(ind: dict) -> None:
    """
    Ajusta los niveles 2 y 3 al número de sublotes del nivel 1:
    elimina sublotes que ya no existen y agrega los que faltan
    (justo después del sublote anterior del mismo lote).
    """
    validos = set(_sublotes(ind['k']))
    for s in ETAPAS:
        orden, vistos = [], set()
        for sb in ind['posiciones'][s]:
            if sb in validos and sb not in vistos:
                orden.append(sb)
                vistos.add(sb)
        for (j, b) in sorted(validos - vistos, key=lambda x: (x[0], x[1])):
            if (j, b - 1) in vistos:
                pos = orden.index((j, b - 1)) + 1
            else:
                pos = random.randint(0, len(orden))
            orden.insert(pos, (j, b))
            vistos.add((j, b))
        ind['posiciones'][s] = orden

        if ind.get('maquinas') is not None:
            maqs = {sb: m for sb, m in ind['maquinas'][s].items() if sb in validos}
            # Se recorre en orden fijo (no el set) para que la semilla sea reproducible
            for (j, b) in orden:
                if (j, b) not in maqs:
                    maqs[(j, b)] = random.choice(elegibles(j, s))
            ind['maquinas'][s] = maqs


def crear_individuo() -> dict:
    """
    Población inicial del ESCENARIO 2 (asignación aleatoria):
      - Nivel 1: número y tamaños de sublote variables (aleatorios),
                 iguales en todas las etapas.
      - Nivel 2: posiciones de los sublotes aleatorias en cada etapa.
      - Nivel 3: máquinas capaces asignadas aleatoriamente.
    """
    k, proporciones = {}, {}
    for j in TRABAJOS:
        k[j] = random.randint(1, _max_k_valido(j))
        proporciones[j] = _dirichlet(k[j])

    subs = _sublotes(k)
    posiciones, maquinas = {}, {}
    for s in ETAPAS:
        orden = subs[:]
        random.shuffle(orden)
        posiciones[s] = orden
        maquinas[s] = {(j, b): random.choice(elegibles(j, s)) for (j, b) in subs}

    return {
        'k'           : k,
        'proporciones': proporciones,
        'posiciones'  : posiciones,
        'maquinas'    : maquinas if ASIGNACION_MAQUINAS == 'cromosoma' else None,
    }

# ---------------------------------------------------------------------------
# 7.  DECODIFICADOR / SIMULADOR HFS CON SUBLOTES CONSISTENTES
# ---------------------------------------------------------------------------

def _primer_hueco(intervalos: List[Tuple[float, float]], t_listo: float,
                  duracion: float) -> float:
    """
    Primer instante >= t_listo en que la máquina tiene un hueco libre de
    longitud 'duracion' ("first available position" del artículo).
    """
    t = t_listo
    for ini, fin in intervalos:
        if t + duracion <= ini + 1e-9:
            return t
        if fin > t:
            t = fin
    return t


def simular_hfs(individuo: dict) -> Tuple[Dict[str, float], Dict[int, list]]:
    """
    Decodifica el cromosoma (esquema de programación serial, etapa por etapa).

    Para cada etapa s y cada sublote (j,b) en el orden del nivel 2:
      * tiempo listo = fin del MISMO sublote (j,b) en la etapa anterior
        (o la liberación del trabajo en la primera etapa),
      * máquina = nivel 3 del cromosoma (o ECT si ASIGNACION_MAQUINAS='ECT'),
      * se programa en el primer hueco disponible de la máquina.
    El tamaño del sublote es el mismo en todas las etapas (consistente).

    Retorna
    -------
    C     : {trabajo: tiempo_de_terminación_en_última_etapa}
    gantt : {etapa: [(trabajo, sublote, maquina, inicio, fin), ...]}
    """
    k        = individuo['k']
    maquinas = individuo.get('maquinas')

    doc = {j: props_a_docenas(j, individuo['proporciones'][j]) for j in TRABAJOS}

    # Tiempo en que cada sublote queda disponible para la siguiente etapa
    listo = {(j, b): RELEASE[j] for j in TRABAJOS for b in range(1, k[j] + 1)}

    agenda: Dict[str, List[Tuple[float, float]]] = {}
    gantt: Dict[int, list] = {s: [] for s in ETAPAS}

    for s in ETAPAS:
        fin_s = {}
        for (j, b) in individuo['posiciones'][s]:
            cant = doc[j][b - 1]
            if cant <= 0:
                fin_s[(j, b)] = listo[(j, b)]
                continue
            t_listo = listo[(j, b)]

            if maquinas is not None:
                candidatas = [maquinas[s][(j, b)]]
            else:
                candidatas = elegibles(j, s)

            mejor = None
            for m in candidatas:
                p   = tiempo_horas(j, m, cant)
                ini = _primer_hueco(agenda.get(m, []), t_listo, p)
                if mejor is None or ini + p < mejor[2] - 1e-9:
                    mejor = (m, ini, ini + p)
            m, ini, fin = mejor

            bisect.insort(agenda.setdefault(m, []), (ini, fin))
            fin_s[(j, b)] = fin
            gantt[s].append((j, b, m, ini, fin))
        listo = fin_s

    C = {j: max(listo[(j, b)] for b in range(1, k[j] + 1)) for j in TRABAJOS}
    return C, gantt

